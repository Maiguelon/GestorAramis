test('un formulario de revisión viejo no reemplaza una versión creada en otra pestaña',async({page,context})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Abrir Tu rincón favorito'}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByRole('tab',{name:'Revisión',exact:true}).click();
  await dialog.getByRole('button',{name:'Preparar nueva versión'}).click();
  await dialog.getByLabel('Texto que revisará el cliente').fill('Borrador viejo que no debe reemplazar el nuevo');
  const second=await context.newPage();
  await second.goto('/');
  await second.getByRole('button',{name:'Abrir Tu rincón favorito'}).click();
  const other=second.getByRole('dialog');
  await other.getByRole('tab',{name:'Revisión',exact:true}).click();
  await other.getByRole('button',{name:'Preparar nueva versión'}).click();
  await other.getByLabel('Texto que revisará el cliente').fill('Versión vigente de la otra pestaña');
  await other.getByRole('button',{name:'Preparar revisión de prueba'}).click();
  await expect(dialog.getByText(/La pieza cambió desde que abriste esta revisión/)).toBeVisible();
  await expect(dialog.getByLabel('Texto que revisará el cliente')).toHaveValue('Borrador viejo que no debe reemplazar el nuevo');
  await dialog.getByRole('button',{name:'Preparar revisión de prueba'}).click();
  await expect(dialog.getByRole('alert')).toBeVisible();
  const saved=await state(page);
  expect(saved.reviews.filter(review=>review.pieceId==='piece-oliva-review')).toHaveLength(2);
  expect(saved.pieces.find(piece=>piece.id==='piece-oliva-review')?.caption).toBe('Versión vigente de la otra pestaña');
  await second.close();
});

