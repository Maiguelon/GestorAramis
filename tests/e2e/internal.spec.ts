  await other.getByLabel('Texto que revisará el cliente').fill('Una versión dos distinta');
  await other.getByRole('button',{name:'Preparar revisión de prueba'}).click();
  await expect(dialog.getByRole('heading',{name:'Versión 2',exact:true})).toBeVisible();
  await expect(dialog.getByLabel('Nombre de quien respondió')).toHaveCount(0);
  await dialog.getByRole('button',{name:'Generar enlace de prueba'}).click();
