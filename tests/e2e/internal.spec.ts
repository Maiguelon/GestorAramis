test('una edición de otra pestaña no pisa el borrador y el guardado persiste al recargar',async({page,context})=>{
  await page.goto('/');
  const trigger=page.getByRole('button',{name:'Abrir Tu rincón favorito'});
  await trigger.click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Nota interna').fill('Borrador todavía sin guardar');
  const second=await context.newPage();
  await second.goto('/');
  await second.getByRole('button',{name:'Abrir Tu rincón favorito'}).click();
  await second.getByRole('dialog').getByLabel('Nota interna').fill('Cambio guardado desde otra pestaña');
  await second.getByRole('button',{name:'Guardar cambios'}).click();
  await expect(dialog.getByText(/La pieza cambió mientras la editabas/)).toBeVisible();
  await expect(dialog.getByLabel('Nota interna')).toHaveValue('Borrador todavía sin guardar');
  await dialog.getByRole('button',{name:'Guardar cambios'}).click();
  await expect(dialog.getByRole('alert')).toContainText('El contenido cambió');
  expect((await state(page)).pieces.find(piece=>piece.id==='piece-oliva-review')?.internalNote).toBe('Cambio guardado desde otra pestaña');
  await dialog.getByRole('button',{name:'Cargar datos actuales'}).click();
  await expect(dialog.getByLabel('Nota interna')).toHaveValue('Cambio guardado desde otra pestaña');
  await dialog.getByRole('button',{name:'Cerrar',exact:true}).click();
  await expect(trigger).toBeFocused();
  await page.reload();
  await page.getByRole('button',{name:'Abrir Tu rincón favorito'}).click();
  await expect(page.getByRole('dialog').getByLabel('Nota interna')).toHaveValue('Cambio guardado desde otra pestaña');
  await second.close();
});

