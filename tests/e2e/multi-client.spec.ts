import { expect, test, type Page } from '@playwright/test';
import type { WorkspaceState } from '../../contracts/domain';

const readState = (page:Page):Promise<WorkspaceState> => page.evaluate(() => JSON.parse(localStorage.getItem('aramis.workspace.demo.v1')!));
test('one shared task persists and is reachable through every chosen client, month, calendar and Design', async ({ page }) => {
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.clock.setFixedTime(new Date('2026-10-18T15:00:00Z'));
  await page.goto('/');
  const before=await readState(page);
  await page.getByRole('button',{name:'Nuevo contenido',exact:true}).click();
  let dialog=page.getByRole('dialog');
  await dialog.getByLabel('Título del contenido').fill('Efeméride para todos');
  await dialog.getByLabel('Cliente',{exact:true}).selectOption(before.clients[1].id);
  await dialog.getByLabel('Varios clientes',{exact:true}).check();
  await dialog.locator('summary').click();
  await expect(dialog.getByRole('checkbox',{name:before.clients[1].name,exact:true})).toBeChecked();
  await dialog.getByLabel('Seleccionar todos',{exact:true}).check();
  await dialog.locator('summary').click();
  await expect(dialog.locator('summary')).toHaveText(`Todos los clientes · ${before.clients.length}`);
  await dialog.getByLabel('Formato').selectOption('story');
  await dialog.getByLabel('Fecha prevista',{exact:true}).fill('2026-10-20');
  await dialog.getByRole('button',{name:'Crear contenido',exact:true}).click();
  dialog=page.getByRole('dialog');
  await expect(dialog.getByRole('heading',{name:'Efeméride para todos',exact:true})).toBeVisible();
  const saved=(await readState(page)).pieces.find(p=>p.title==='Efeméride para todos')!;
  expect(saved.clientId).toBe(before.clients[1].id);
  expect(new Set(saved.clientIds)).toEqual(new Set(before.clients.map(c=>c.id)));
  expect((await readState(page)).pieces.length).toBe(before.pieces.length+1);
  await dialog.getByRole('button',{name:'Pasar a producción',exact:true}).click();
  await dialog.getByRole('button',{name:'Cerrar',exact:true}).click();
  await page.reload();
  const row=page.getByRole('button',{name:'Abrir Efeméride para todos',exact:true});
  await expect(row).toHaveCount(1);
  await expect(row.getByRole('img',{name:`Multicliente · ${before.clients.length} clientes`,exact:true})).toBeVisible();
  await expect(row.locator('img')).toHaveCount(0);
  await row.screenshot({path:'work/multi-client-pending-row.png'});
  for (const client of before.clients) {
    await page.getByLabel('Filtrar por cliente',{exact:true}).selectOption(client.id);
    await expect(row).toHaveCount(1);
  }
  await page.getByRole('button',{name:'Calendario',exact:true}).click();
  await expect(page.locator('[data-date="2026-10-20"]').getByRole('button',{name:'Abrir Efeméride para todos',exact:true})).toHaveCount(1);
  const calendarTitle=page.locator('[data-date="2026-10-20"]').getByRole('button',{name:'Abrir Efeméride para todos',exact:true}).locator('strong');
  expect(await calendarTitle.evaluate(element=>{const title=element.getBoundingClientRect(),card=element.closest('button')!.getBoundingClientRect();return title.y>=card.y&&title.bottom<=card.bottom;})).toBe(true);
  await page.locator('[data-date="2026-10-20"]').screenshot({path:'work/multi-client-calendar-day.png'});
  await page.getByLabel('Filtrar por cliente',{exact:true}).selectOption(before.clients[0].id);
  await expect(page.locator('[data-date="2026-10-20"]').getByRole('button',{name:'Abrir Efeméride para todos',exact:true})).toHaveCount(1);
  await page.getByRole('button',{name:'Clientes',exact:true}).click();
  await page.locator('.brand-card').filter({has:page.getByRole('heading',{name:before.clients[0].name,exact:true})}).getByRole('button',{name:'Trabajar mes'}).click();
  await page.getByLabel('Mes de trabajo',{exact:true}).fill('2026-10');
  await expect(page.getByRole('form',{name:'Editar Efeméride para todos',exact:true})).toBeVisible();
  await expect(page.getByText('Multicliente · extra',{exact:true})).toBeVisible();
  await page.getByLabel('Vista de trabajo',{exact:true}).selectOption('design');
  await page.getByLabel('Filtrar por cliente',{exact:true}).selectOption(before.clients[0].id);
  await expect(page.locator('.design-task').filter({has:page.getByRole('heading',{name:'Efeméride para todos',exact:true})})).toHaveCount(1);
  await page.getByRole('article',{name:'Efeméride para todos',exact:true}).getByRole('button',{name:'Abrir pieza',exact:true}).click();
  const textPage=page.waitForEvent('popup');
  await page.getByRole('dialog').getByRole('link',{name:'Abrir texto completo'}).click();
  const popup=await textPage;
  await expect(popup.locator('.piece-text-client')).toContainText(before.clients[2].name);
  await popup.close();
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('dialog').getByRole('button',{name:'Archivar',exact:true}).click();
  await page.getByLabel('Vista de trabajo',{exact:true}).selectOption('management');
  await page.getByRole('button',{name:'Historial',exact:true}).click();
  await page.getByRole('button',{name:'Archivados',exact:true}).click();
  await page.getByLabel('Cliente del historial',{exact:true}).selectOption(before.clients[2].id);
  await expect(page.getByRole('button',{name:'Abrir Efeméride para todos',exact:true})).toHaveCount(1);
  expect(errors).toEqual([]);
});

test('recipient selector preserves the single client and rejects an empty selection on mobile', async ({ page }) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.getByRole('button',{name:'Nuevo contenido',exact:true}).click();
  const dialog=page.getByRole('dialog'), state=await readState(page);
  await dialog.getByLabel('Cliente',{exact:true}).selectOption(state.clients[1].id);
  await dialog.getByLabel('Varios clientes',{exact:true}).check();
  await dialog.locator('summary').click();
  await dialog.getByLabel('Seleccionar todos',{exact:true}).check();
  await dialog.getByLabel('Seleccionar todos',{exact:true}).uncheck();
  await dialog.locator('summary').click();
  await dialog.getByRole('button',{name:'Crear contenido',exact:true}).click();
  await expect(dialog.getByRole('alert')).toHaveText('Elegí al menos un cliente.');
  expect((await readState(page)).pieces).toHaveLength(state.pieces.length);
  await dialog.getByLabel('Varios clientes',{exact:true}).uncheck();
  await dialog.getByLabel('Cliente',{exact:true}).selectOption(state.clients[1].id);
  await dialog.getByLabel('Varios clientes',{exact:true}).check();
  await dialog.getByLabel('Varios clientes',{exact:true}).uncheck();
  await expect(dialog.getByLabel('Cliente',{exact:true})).toHaveValue(state.clients[1].id);
  await expect(dialog.getByRole('alert')).toHaveCount(0);
  await dialog.getByLabel('Varios clientes',{exact:true}).check();
  expect(await dialog.evaluate(element=>element.scrollWidth<=element.clientWidth)).toBe(true);
  await dialog.screenshot({path:'work/multi-client-create-mobile.png'});
});
